import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build, version as esbuildVersion } from "esbuild";

const require = createRequire(import.meta.url);
const root = fileURLToPath(new URL("..", import.meta.url));
const source = require.resolve("marked");
const packageRoot = resolve(dirname(source), "..");
const metadata = JSON.parse(await readFile(resolve(packageRoot, "package.json"), "utf8"));
if (metadata.version !== "18.1.1") throw Error("Unexpected Markdown dependency version");
const output = resolve(root, "shared/conversation/vendor");
await mkdir(output, { recursive: true });
await build({
  stdin: {
    contents: 'export {Marked} from "marked";',
    resolveDir: root,
    sourcefile: "marked-entry.js",
  },
  bundle: true,
  platform: "neutral",
  target: "es2020",
  format: "esm",
  legalComments: "eof",
  banner: { js: "// Generated by build:markdown. Marked 18.1.1, MIT; see marked.LICENSE.md." },
  outfile: resolve(output, "marked.js"),
});
await writeFile(
  resolve(output, "marked.d.ts"),
  'import type {Marked as MarkedConstructor} from "marked";\nexport declare const Marked: typeof MarkedConstructor;\n',
);
await writeFile(
  resolve(output, "marked.LICENSE.md"),
  await readFile(resolve(packageRoot, "LICENSE")),
);
const digest = createHash("sha256")
  .update(await readFile(source))
  .digest("hex");
await writeFile(
  resolve(output, "marked-source.json"),
  `${JSON.stringify(
    {
      name: "marked",
      version: metadata.version,
      source: "https://registry.npmjs.org/marked/-/marked-18.1.1.tgz",
      entry: "lib/marked.esm.js",
      sha256: digest,
      generatedBy: `esbuild ${esbuildVersion}`,
      license: metadata.license,
    },
    null,
    2,
  )}\n`,
);
process.stdout.write("Bundled Marked 18.1.1 with license and source digest.\n");
